package com.evansong.backend.model;

public class TiempoLiturgico {
    private int idTiempo;
    private String nombre;

    public TiempoLiturgico() {}

    public int getIdTiempo() { return idTiempo; }
    public void setIdTiempo(int idTiempo) { this.idTiempo = idTiempo; }
    public String getNombre() { return nombre; }
    public void setNombre(String nombre) { this.nombre = nombre; }
}
